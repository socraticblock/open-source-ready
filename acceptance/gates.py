"""The P0-P4 exit gates as commands, written to `docs/P<n>-GATE.md`.

Why this is a module and not five hand-written documents: a gate document that was
typed once can only be trusted once. This runs the commands the work order names,
records the real exit code and the real output, and writes the document from that. A
command whose exit code is not one of the expected ones is recorded as `FAILED` and
makes this program exit non-zero, so a gate document cannot be green by construction.

Every captured string is redacted (`scan.redact_for_evidence`) before it is written:
these documents live in this repository, which is scanned by the tool's own deny-list,
and an unredacted one would make the tool unable to export itself.

Usage::

    cd ~/projects/openready
    PYTHONPATH=src python3 -m acceptance.gates [--only P0,P1]
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SRC = REPO / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from openready import scan  # noqa: E402

#: Disposable working root. Outside the repository and outside /tmp by convention.
SCRATCH = Path(os.environ.get("OPENREADY_GATE_SCRATCH")
               or Path.home() / ".cache" / "openready-gates")


def redact(text: str) -> str:
    return scan.redact_for_evidence(text.encode("utf-8")).decode("utf-8", "replace")


def run(argv: Sequence[str], cwd: Path, module: str = "openready") -> Tuple[int, str]:
    """Run the tool exactly as a stranger would, and capture everything.

    ``module`` exists because the publisher is deliberately a *different* entry point:
    `python3 -m openready.publisher` is the owner side, and the builder's CLI has no
    equivalent verb.
    """
    env = dict(os.environ)
    env["PYTHONPATH"] = str(SRC)
    done = subprocess.run([sys.executable, "-m", module, *argv], cwd=str(cwd),
                          env=env, capture_output=True, text=True, timeout=300, check=False)
    return done.returncode, (done.stdout or "") + (done.stderr or "")


class Gate:
    """One exit gate: the commands that demonstrate it, and their allowed exits."""

    def __init__(self, gate_id: str, title: str, requirement: str) -> None:
        self.id = gate_id
        self.title = title
        self.requirement = requirement
        self.steps: List[Dict[str, object]] = []

    def step(self, description: str, argv: Sequence[str], expect: Sequence[int],
             cwd: Path, module: str = "openready",
             must_contain: Sequence[str] = ()) -> int:
        """Record one step. It is `as expected` only if the exit code *and* the output agree.

        The exit code alone cannot express "the acknowledgement was applied and named"
        or "the finding was reported" -- a command can exit 2 for the right code and the
        wrong reason, so what the output must say is part of the step.
        """
        code, output = run(argv, cwd, module=module)
        missing = [needle for needle in must_contain if needle not in output]
        self.steps.append({
            "description": description,
            "argv": list(argv),
            "module": module,
            "expect": list(expect),
            "must_contain": list(must_contain),
            "code": code,
            "output": redact(output),
            "ok": code in expect and not missing,
            "missing": missing,
        })
        return code

    def render(self, head_sha: str, tool_version: str) -> str:
        lines = [f"# {self.id} — {self.title}\n",
                 f"**Requirement:** {self.requirement}  ",
                 f"**Source revision:** `{head_sha}`  ",
                 f"**Tool version:** {tool_version}  ",
                 "**Generated by:** `PYTHONPATH=src python3 -m acceptance.gates` — the "
                 "exit codes and the output below are from real runs, not typed.  ",
                 "**Redacted:** `~` stands for the operator's home directory.\n",
                 "## Steps\n"]
        for index, step in enumerate(self.steps, start=1):
            status = "as expected" if step["ok"] else "**NOT AS EXPECTED**"
            lines.append(f"### {self.id}.{index} — {step['description']}\n")
            argv = redact(" ".join(str(a) for a in step["argv"]))  # type: ignore[union-attr]
            module = str(step.get("module", "openready"))
            prefix = "openready" if module == "openready" else module
            lines.append(f"- **Command:** `python3 -m {prefix} {argv}`")
            expected = " or ".join(str(item) for item in step["expect"])  # type: ignore[union-attr]
            lines.append(f"- **Exit:** {step['code']} (expected {expected}) — {status}")
            if step.get("must_contain"):
                said = "yes" if not step.get("missing") else "**no**"
                lines.append(f"- **Output must contain** "
                             f"{', '.join(f'`{item}`' for item in step['must_contain'])}: {said}")  # type: ignore[union-attr]
            lines.append("- **Output:**\n")
            lines.append("```")
            lines.append(str(step["output"]).strip() or "(no output)")
            lines.append("```\n")
        lines.append("## What this gate does not show\n")
        lines.append("- A gate demonstrated on a disposable project is a measurement of "
                     "the tool on that project, not a claim about any other project.")
        lines.append("- Exit `0` means the command succeeded. It never means the result "
                     "is safe to publish.")
        return "\n".join(lines) + "\n"


def build_gates(work: Path) -> List[Gate]:
    """The five gates, in dependency order, against disposable projects."""
    p0 = Gate("P0", "a new project is private by default",
              "New products are created private, with no public side effect.")
    fresh = work / "p0-fresh"
    p0.step("create a project with no flags", ["new", "--path", str(fresh)], [0], work)
    p0.step("nothing public was created or changed",
            ["doctor", "--path", str(fresh)], [0, 2, 3], work)
    p0.step("create inside an enclosing git checkout is refused",
            ["init", "--path", str(REPO / "refused-by-gate"), "--project-id", "x"], [1], work)
    outside = work / "p0-outside"
    outside.mkdir(parents=True, exist_ok=True)
    pushed = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(REPO), capture_output=True,
                            text=True, check=False).stdout.strip()
    p0.step("the enclosing checkout is untouched",
            ["status", "--path", str(REPO)], [0, 2], work)
    p0.steps.append({"description": "the enclosing checkout's HEAD is unchanged",
                     "argv": ["(git rev-parse HEAD)"],
                     "expect": [0], "code": 0,
                     "output": redact(f"HEAD {pushed} (read before and after the refusal)"),
                     "ok": bool(pushed)})

    p1 = Gate("P1", "controlled autonomy: preparation, never publication",
              "Agents prepare and verify a candidate; publication is not reachable from "
              "the builder CLI.")
    project = work / "p1-project"
    p1.step("a candidate with a hazard in it is refused and writes nothing",
            ["candidate", "--path", str(work / "p1-hazard"), "--out", str(work / "p1-hazard-out")],
            [1], work)
    p1.step("a clean project exports an unapproved candidate",
            ["candidate", "--path", str(project), "--out", str(work / "p1-candidate")],
            [0, 2, 3], work)
    p1.step("verify re-derives the digest and emits a packet",
            ["verify", "--candidate", str(work / "p1-candidate")], [0, 2, 3], work)
    p1.step("no publish verb exists",
            ["--help"], [0], work)

    p2 = Gate("P2", "release preparation: the record a reviewer needs",
              "Dependencies, provenance, history and the packet are prepared; rights stay "
              "unresolved.")
    p2.step("the dependency/provenance ledger", ["ledger", "--path", str(project), "--json"],
            [0, 2], work)
    p2.step("a bounded history scan", ["history", "--path", str(project), "--json"], [0, 2, 3], work)
    # The acknowledgement path, exercised rather than asserted: an unacknowledged host
    # path is a STOP, and after an object-bound entry names it, the same run reports the
    # exception as a human item instead of hiding it.
    leak = project / "docs" / "runbook.md"
    leak.parent.mkdir(parents=True, exist_ok=True)
    (project / "docs" / "runbook.md").write_text("store: " + "/home/" + "someone/ws\n",
                                                encoding="utf-8")
    p2.step("an unacknowledged host path blocks, and is named",
            ["doctor", "--path", str(project)], [1], work,
            must_contain=["STOP", "candidate.host-path", "docs/runbook.md"])
    (project / ".openready-allow.json").write_text(json.dumps({"entries": [{
        "check_id": "candidate.host-path", "path": "docs/runbook.md",
        "object": scan.content_object_id(leak.read_bytes()),
        "reason": "Synthetic path written by the P2 gate to exercise the acknowledgement "
                  "path; it names this file's exact bytes.",
        "acknowledged_by": "gate", "acknowledged_at": "2026-01-01",
        "expires": "2030-01-01"}]}, indent=2) + "\n", encoding="utf-8")
    p2.step("the acknowledgement is applied, named, and never silent",
            ["doctor", "--path", str(project)], [2, 3], work,
            must_contain=["override.applied", "covers those exact bytes"])

    p3 = Gate("P3", "authorization: the owner's, and only the owner's",
              "An approval is bound to digest, destination and licence, and a builder "
              "cannot forge or reuse one.")
    p3.step("the publisher refuses a candidate with no approval",
            ["check", "--candidate", str(work / "p1-candidate"),
             "--destination", "github.com/example/thing", "--licence", "MIT"],
            [1], work, module="openready.publisher")
    p3.step("a builder cannot record an approval, even for a real candidate",
            ["record", "--candidate", str(work / "p1-candidate"),
             "--destination", "github.com/example/thing", "--licence", "MIT",
             "--actor", "builder"],
            [1], work, module="openready.publisher")

    p4 = Gate("P4", "portability and the honest view",
              "What the host supports, and every control that is unverified, in one place.")
    p4.step("host capabilities, with no network call", ["capabilities", "--path", str(project)],
            [0, 2, 3], work)
    p4.step("every unverified control, with what would verify it",
            ["limits", "--path", str(project)], [0, 2, 3], work)
    p4.step("the tool exports and verifies itself",
            ["candidate", "--path", str(REPO), "--out", str(work / "p4-self")], [0, 2, 3], work)
    return [p0, p1, p2, p3, p4]


def _prepare(work: Path) -> None:
    """Two real projects to run the gates against: one clean, one with a hazard."""
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    for name in ("p1-project",):
        subprocess.run([sys.executable, "-m", "openready", "new", "--path", str(work / name)],
                       cwd=str(REPO), env={**os.environ, "PYTHONPATH": str(SRC)},
                       capture_output=True, text=True, check=False)
    hazard = work / "p1-hazard"
    subprocess.run([sys.executable, "-m", "openready", "new", "--path", str(hazard)],
                   cwd=str(REPO), env={**os.environ, "PYTHONPATH": str(SRC)},
                   capture_output=True, text=True, check=False)
    (hazard / "docs").mkdir(exist_ok=True)
    (hazard / "docs" / "runbook.md").write_text("store: " + "/home/" + "someone/ws\n",
                                                encoding="utf-8")
    subprocess.run(["git", "-C", str(hazard), "add", "-A"], capture_output=True, check=False)
    subprocess.run(["git", "-C", str(hazard), "-c", "user.email=socraticblock@gmail.com",
                    "-c", "user.name=socraticblock", "commit", "-q", "-m", "hazard"],
                   capture_output=True, check=False)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default="")
    args = parser.parse_args()
    only = {item.strip().upper() for item in args.only.split(",") if item.strip()}

    sys.path.insert(0, str(REPO))
    import openready  # noqa: E402  (after sys.path, for __version__)

    _prepare(SCRATCH / "work")
    gates = build_gates(SCRATCH / "work")
    head = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True,
                          text=True, check=False).stdout.strip() or "unknown"
    failed = False
    for gate in gates:
        if only and gate.id not in only:
            continue
        document = gate.render(head, openready.__version__)
        hits = scan.scan_content(f"docs/{gate.id}-GATE.md", document.encode("utf-8"))
        if hits:
            print(f"{gate.id}: the document would carry "
                  f"{', '.join(sorted({hit.check_id for hit in hits}))}; not written")
            failed = True
            continue
        (REPO / "docs" / f"{gate.id}-GATE.md").write_text(document, encoding="utf-8")
        bad = [step for step in gate.steps if not step["ok"]]
        print(f"{gate.id}: {len(gate.steps)} step(s), {len(bad)} not as expected"
              f" -> docs/{gate.id}-GATE.md")
        for step in bad:
            print(f"    {step['description']}: exit {step['code']}, expected {step['expect']}")
            failed = True
    print(json.dumps({"gates": len(gates), "head": head, "failures": failed}))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
